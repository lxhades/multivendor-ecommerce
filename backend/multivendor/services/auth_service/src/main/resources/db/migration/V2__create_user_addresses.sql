CREATE TABLE public.user_addresses (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    receiver_name varchar(255) NOT NULL,
    phone varchar(255) NOT NULL,
    location varchar(255) NOT NULL,
    detail varchar(255) NOT NULL,
    is_default boolean NOT NULL DEFAULT false,
    user_id uuid NOT NULL,
    CONSTRAINT pk_user_addresses PRIMARY KEY (id),
    CONSTRAINT fk_user_addresses_user FOREIGN KEY (user_id) REFERENCES public.users (id) ON DELETE CASCADE,
    CONSTRAINT ck_user_addresses_receiver_name CHECK (length(btrim(receiver_name)) > 0),
    CONSTRAINT ck_user_addresses_phone_length CHECK (length(phone) >= 8),
    CONSTRAINT ck_user_addresses_location CHECK (length(btrim(location)) > 0),
    CONSTRAINT ck_user_addresses_detail CHECK (length(btrim(detail)) > 0)
);
COMMENT ON TABLE public.user_addresses IS 'Delivery addresses of an Auth account.';
